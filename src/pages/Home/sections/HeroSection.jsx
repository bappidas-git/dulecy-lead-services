/* ============================================
   Home / Hero — ported 1:1 from `mockup/index.html`
   --------------------------------------------
   Parallaxed Unsplash backdrop under a double white scrim, a floating
   Dulcey "DLS" mark, then the badge → headline → lede → CTAs → four pillars,
   all staggered in on load by `useHeroIntro` (the mockup's `data-hero`
   elements, marked with the same attribute here).

   The backdrop photo is a deliberate departure from `mockup/index.html`,
   which uses an architectural shot here: it is a handshake framed at forearm
   level, with neither head in shot. It fills the whole section at every
   width — `object-fit: cover` on a box that is the hero plus the parallax's
   overscan — under a white overlay that fades out from left to right, so the
   copy sits on white and the clasp on clear photo. The scrim alphas depart
   from the mockup for the same reason. See the annotated `.bg` / `.scrim`
   blocks in the stylesheet.
   ============================================ */

import React from 'react';
import { Link } from 'react-router-dom';
import { useModal } from '../../../context/ModalContext';
import { siteConfig, MARK_SIZE } from '../../../data/siteConfig';
import { useHeroIntro, useParallax, parallaxPreset } from '../../../animations';
import layout from '../../../styles/layout.module.css';
import styles from './HeroSection.module.css';

// Self-hosted backdrop (Prompt 12) — generated by `npm run generate:images`.
// Preloaded in `public/index.html`, so the two must be kept in sync.
//
// `-v3` supersedes the `hero-home-v2` files rather than replacing them in
// place: `/images/**` answers `immutable` for a year (see `public/.htaccess`),
// so a same-name swap would leave every returning visitor on the old crop.
// Same client photo, re-cut for the full-bleed treatment — the generator
// trims the master's right edge to 4050x1900 and ships one 2880w variant.
//
// One width, and no `sizes`, on purpose. A full-bleed `cover` backdrop is
// scaled by the section's HEIGHT, not its width (the hero is always taller
// than 1/2.13 of its width), so the rendered width barely moves with the
// viewport — 2180 to 2635 CSS px from 320px to 1920px. A `sizes` written in
// `vw` would describe the wrong quantity, and every breakpoint would resolve
// to the same variant anyway. 2880w covers the widest of those, so the photo
// is never drawn beyond its natural size, and it is 47 KB.
const HERO_BG = '/images/hero-home-v3.jpg';
const HERO_BG_WEBP = '/images/hero-home-v3-2880.webp';

const PILLARS = [
  { num: '01', label: 'Business Solutions' },
  { num: '02', label: 'People & Organization' },
  { num: '03', label: 'Corporate Services' },
  { num: '04', label: 'Leadership & Capability' },
];

const HeroSection = () => {
  const { openLeadModal } = useModal();
  const heroRef = useHeroIntro();
  const bgRef = useParallax(parallaxPreset(-16));

  return (
    <section className={styles.hero}>
      {/* `display: contents` on the <picture> keeps the absolutely
          positioned <img> laid out exactly as it was before the wrapper. */}
      <picture className={styles.bgPicture}>
        <source type="image/webp" srcSet={HERO_BG_WEBP} />
        <img
          ref={bgRef}
          className={styles.bg}
          src={HERO_BG}
          alt=""
          aria-hidden="true"
          width="4050"
          height="1900"
          fetchpriority="high"
          decoding="async"
        />
      </picture>
      <div className={styles.scrim} aria-hidden="true" />

      <div ref={heroRef} className={`${layout.container} ${styles.inner}`}>
        {/* Decorative floating mark — the self-hosted "DLS" initialism, drawn
            up to 430px wide and shipped at 860px so it stays crisp at 2×.
            `MARK_SIZE` reserves the 1.87:1 box; the stylesheet sets the
            rendered width and leaves the height auto. */}
        <img
          className={styles.float}
          src={siteConfig.logoMark}
          alt=""
          aria-hidden="true"
          width={MARK_SIZE.width}
          height={MARK_SIZE.height}
          decoding="async"
        />

        <div className={styles.badge} data-hero>
          <span className={styles.dot} aria-hidden="true" /> {siteConfig.tagline}
        </div>

        {/* Deliberate departure from `mockup/index.html`, which stops both
            clauses with a full stop. The comma carries the first line into the
            second, and the headline closes on the word "impact" itself rather
            than on a mark — at every width, since this is one string wrapped by
            a single unconditional <br />. */}
        <h1 className="display" data-hero>
          We don&rsquo;t just offer services,
          <br />
          We deliver <em className={`grad-text ${styles.impact}`}>impact</em>
        </h1>

        <p className={`lede ${styles.lede}`} data-hero>
          <b className="brand">{siteConfig.brandName}</b> works with businesses,
          institutions, entrepreneurs, and professionals to navigate complexity,
          strengthen organizational capability, and build for sustainable
          growth.
        </p>

        <div className={styles.cta} data-hero>
          <button
            type="button"
            className="btn btn--primary"
            onClick={() => openLeadModal('home-hero')}
          >
            Start a Conversation <span aria-hidden="true">&rarr;</span>
          </button>
          <Link to="/expertise" className="btn btn--outline">
            Explore Our Expertise
          </Link>
        </div>

        <div className={styles.pillars} data-hero>
          {PILLARS.map((pillar) => (
            <div key={pillar.num}>
              <b>{pillar.num}</b>
              <span>{pillar.label}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
};

export default HeroSection;
