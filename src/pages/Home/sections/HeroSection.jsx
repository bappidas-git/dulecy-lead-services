/* ============================================
   Home / Hero — ported 1:1 from `mockup/index.html`
   --------------------------------------------
   A photographic backdrop, then the badge → headline → lede → CTAs → four
   pillars, all staggered in on load by `useHeroIntro` (the mockup's
   `data-hero` elements, marked with the same attribute here).

   The backdrop photo is a deliberate departure from `mockup/index.html`, which
   uses an architectural shot here: it is a handshake framed at forearm level
   against a blown-out white window.

   **The frame is drawn whole, at a stated width, and the section clips it.**
   There is no fitting box and no CSS-decided crop — `width: var(--bg-w);
   height: auto` on a 2.63:1 file is the entire sizing rule — so what the page
   shows is decided only by where the hero's edges fall across the photograph,
   and the placement is set so those edges land where the frame carries nothing:
   the blown-out window on the left, the far sleeve's outer end past the right.
   Three of the four edges end inside the section and are feathered to nothing
   so they dissolve rather than cut; the right one runs off the page, so
   `overflow: hidden` ends it the way a viewport ends any full-bleed image.

   The feather is an eased curve — smootherstep cubed — sampled at twentieths,
   and both of those matter. A CSS gradient is piecewise-linear between its
   stops, so what reads as a line in a soft ramp is not its steepness but any
   place its SLOPE changes: a curve that arrives at full strength still moving
   (the `t^2.4` this replaced) puts a corner where the ramp meets the flat
   middle of the mask, and a coarsely sampled one puts a smaller corner at
   every stop. Same rule governs every ramp in the overlay below.

   That placement is what puts the subject where the brief wants it. The joined
   hands are a measured 56.1%-81.1% of the frame's width, so pinning it 11% past
   the hero's right edge always leaves 8% of frame between their right edge and
   the screen — the arm reads as continuing, and the hands are never the thing
   that gets cut. Their left edge lands beside the headline: 22px past where it
   ends at 1440px, further out as the viewport grows, and just inside it below
   about 1330px, where the copy owns too much of a narrow hero for anything
   else. At 1440px that is 331px of hand against the 265px the release before
   this one drew.

   Over it sits a white overlay, and from 920px up that overlay is two layers
   rather than one, because the suited figure the hands belong to stands
   directly behind the headline at every desktop width — there is no strip of
   hero where the figure is and the copy is not, so no left-to-right fade can
   uncover it. A flat 0.40 base carries the whole copy column and lets go
   within 10% of the hero after the glyphs end, which is also where the hand
   starts; a second layer, masked to the band of hero the red accent sits in,
   brings the white back to 0.85 over "impact" alone — the one run of copy
   that is colour-bound rather than ink-black, and the one number in the
   section that is fixed rather than tuned. Below the breakpoint the copy
   spans the frame, so a vertical veil takes over legibility and the fade is
   left to do nothing but keep the left edge clean. See the annotated `.bg`
   and `.scrim` blocks in the stylesheet.
   ============================================ */

import React from 'react';
import { Link } from 'react-router-dom';
import { useModal } from '../../../context/ModalContext';
import { siteConfig } from '../../../data/siteConfig';
import { useHeroIntro } from '../../../animations';
import layout from '../../../styles/layout.module.css';
import styles from './HeroSection.module.css';

// Self-hosted backdrop — generated by `npm run generate:images`. Preloaded in
// `public/index.html`, so the two must be kept in sync.
//
// `-v6` supersedes the `hero-home-v5` files rather than replacing them in
// place: `/images/**` answers `immutable` for a year (see `public/.htaccess`),
// so a same-name swap would leave every returning visitor on the old photo. It
// is the 5000x1900 (2.63:1) client master that once shipped as `hero-home-v4`,
// back again — but under a third basename for that same caching reason, not
// revived under the old one.
//
// One width, and no `sizes`: the frame is drawn at exactly `--bg-w`, which
// caps at 1900 CSS px from 920px up and 1400 CSS px below it — comfortably
// inside 2x this file on a retina display, so it never upscales — and the
// shallow depth of field keeps it at 39 KB.
//
// **The WebP is the only variant the hero paints.** There is no `<picture>` and
// no `image-set()` fallback, which costs less than it sounds: an `<img src>` on
// a WebP is supported back to Safari 14 and Chrome 32, a WIDER floor than
// `image-set()` with `type()` (Safari 17, Chrome 113) would have given. Older
// engines than that get no backdrop, which the section survives intact — the
// image is decorative and `aria-hidden`, the overlay above it is white, and
// every glyph in the hero is specified against white first.
//
// `public/images/hero-home-v6.jpg` is still emitted next to it — every photo in
// `generate-images` gets a universal JPEG fallback — and is simply not
// referenced from anywhere; it is the file a `<picture>` here would need.
//
// `HERO_BG` is the third place this filename lives, after `generate-images` and
// the LCP preload in `public/index.html`; keep it in sync with the preload.
const HERO_BG = '/images/hero-home-v6-2880.webp';

// The intrinsic size of that file. Passed through as the `width`/`height`
// attributes so the box has an aspect ratio before the bytes land; the
// stylesheet then sets `width: var(--bg-w)` and leaves `height: auto`, which
// draws the whole 2.63:1 frame at that width.
const HERO_BG_SIZE = { width: 2880, height: 1094 };

const PILLARS = [
  { num: '01', label: 'Business Solutions' },
  { num: '02', label: 'People & Organization' },
  { num: '03', label: 'Corporate Services' },
  { num: '04', label: 'Leadership & Capability' },
];

const HeroSection = () => {
  const { openLeadModal } = useModal();
  const heroRef = useHeroIntro();

  return (
    <section className={styles.hero}>
      {/* The backdrop and the overlay: two elements, one treatment — keep them
          grouped. Only `.scrim` is `inset: 0`, which is what makes the fade's
          stops section percentages; the photograph is a placed element sized
          and positioned by the `--bg-*` custom properties on `.hero`.

          It is a real `<img>` rather than a CSS background, and that is what
          lets the stylesheet's edge feather be expressed in percentages of the
          image itself: the element IS the drawn photograph, at its own stated
          width with no box fitted around it. A background would keep the
          element at full section size with the framing baked in, and the
          feather would have nothing fixed to aim at. Being an `<img>` also
          earns `fetchpriority="high"`, which a background cannot carry.

          The `width`/`height` attributes are the file's intrinsic size, so the
          box has an aspect ratio before the bytes land; the stylesheet sets
          `width` and leaves `height: auto`, which is what draws the whole
          2.63:1 frame rather than a crop of it.

          It stays decorative: empty `alt` plus `aria-hidden`, since the hero's
          meaning is entirely in the copy beside it.

          No `useParallax` here, unlike the Expertise and Who We Serve heroes.
          Scrub parallax would slide the subject out of the relationship with
          "impact" that the placement exists to hold. The backdrop is static on
          purpose. */}
      <img
        className={styles.bg}
        src={HERO_BG}
        alt=""
        aria-hidden="true"
        width={HERO_BG_SIZE.width}
        height={HERO_BG_SIZE.height}
        fetchpriority="high"
        decoding="async"
      />
      <div className={styles.scrim} aria-hidden="true" />

      <div ref={heroRef} className={`${layout.container} ${styles.inner}`}>
        <div className={styles.badge} data-hero>
          <span className={styles.dot} aria-hidden="true" /> {siteConfig.tagline}
        </div>

        {/* Deliberate departure from `mockup/index.html`, which stops both
            clauses with a full stop. The comma carries the first line into the
            second, and the headline closes on the word "impact" itself rather
            than on a mark — at every width, since this is one string wrapped by
            a single unconditional <br />. */}
        <h1 className="display" data-hero>
          We don&rsquo;t just offer services,
          <br />
          We deliver <em className={`grad-text ${styles.impact}`}>impact</em>
        </h1>

        <p className={`lede ${styles.lede}`} data-hero>
          <b className="brand">{siteConfig.brandName}</b> works with businesses,
          institutions, entrepreneurs, and professionals to navigate complexity,
          strengthen organizational capability, and build for sustainable
          growth.
        </p>

        <div className={styles.cta} data-hero>
          <button
            type="button"
            className="btn btn--primary"
            onClick={() => openLeadModal('home-hero')}
          >
            Start a Conversation <span aria-hidden="true">&rarr;</span>
          </button>
          <Link to="/expertise" className="btn btn--outline">
            Explore Our Expertise
          </Link>
        </div>

        <div className={styles.pillars} data-hero>
          {PILLARS.map((pillar) => (
            <div key={pillar.num}>
              <b>{pillar.num}</b>
              <span>{pillar.label}</span>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
};

export default HeroSection;
